#[test]
fn test_points_to_angles() {
    const FRAC_PI_4: f64 = 0.785398163397448309615660845819875721;

    let points = vec![
        Point { x: 0, y: 0 },
        Point { x: 10, y: 10 },
        Point { x: 20, y: 20 },
        Point { x: 10, y: 10 },
        Point { x: 10, y: 10 },
        Point { x: 0, y: 0 },
        Point { x: 0, y: 10 },
        Point { x: 10, y: 10 },
    ];
    let recognizer = AngleRecognizer::new();

    let angles = recognizer.points_to_angles(&points);
    assert_eq!(
        angles,
        vec![
            -FRAC_PI_4,
            -FRAC_PI_4,
            -FRAC_PI_4,
            -FRAC_PI_4,
            2.356194490192345,
            -2.504536715598747,
            -0.5620315286694877,
        ]
    )
}
